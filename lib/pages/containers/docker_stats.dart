// Live resource use per container, and the parser for `docker stats`.
//
// The container list answers "is it up". This answers the question a phone is
// usually opened to settle: which one is eating the box. `docker ps` cannot say
// — it has no resource columns at all — and without this the only way to find a
// runaway container from a phone is to open a shell and type `top`.

/// The command that reads one snapshot of every running container's resource
/// use.
///
/// `--no-stream` is not a preference, it is the difference between a command
/// that returns and one that does not: without it `docker stats` prints a line,
/// then keeps printing forever, and the SSH command never completes.
///
/// The format is pipe-delimited for the same reason the `docker ps` format is —
/// the columns are aligned by the daemon and a value containing a space would
/// otherwise shift them. No column here can contain a pipe: a container name
/// cannot, and the percentages and byte counts are generated by the daemon.
///
/// A stopped container is not listed at all, which is why the callers treat a
/// missing entry as "no numbers to show" rather than as an error.
const String dockerStatsCommand =
    "docker stats --no-stream --format "
    "'{{.Name}}|{{.CPUPerc}}|{{.MemUsage}}|{{.MemPerc}}|{{.PIDs}}'";

/// One container's resource use at the moment the snapshot was taken.
class ContainerStats {
  /// Container name, as `docker ps` reports it (no leading slash).
  final String name;

  /// CPU use as a percentage of one core. The daemon can report more than 100
  /// when a container is using several cores at once.
  final double cpuPercent;

  /// Memory in use, in the daemon's own units — `49.06MiB`.
  ///
  /// The container's own figure only. `docker stats` writes this column as
  /// `49.06MiB / 2GiB`, and the half after the slash is deliberately dropped:
  /// with no `--memory` set the daemon puts the HOST's total RAM there, so one
  /// container on this machine reports `1.625MiB / 125.4GiB` while being
  /// unbounded. Nothing in the output distinguishes that from a real 2 GiB cap,
  /// so the honest move is to show the amount in use — true either way — and
  /// make no claim at all about a ceiling.
  ///
  /// Kept as the string the daemon printed rather than converted to bytes: it
  /// is already in the form the user reads, and re-rendering it would introduce
  /// a second rounding of the same number.
  final String memoryUsed;

  /// Memory use as a percentage — of the container's limit when it has one, of
  /// the host's memory when it does not. Meaningful either way, which is why it
  /// survives where the absolute ceiling does not.
  final double memoryPercent;

  /// Number of processes inside the container.
  final int pids;

  const ContainerStats({
    required this.name,
    required this.cpuPercent,
    required this.memoryUsed,
    required this.memoryPercent,
    required this.pids,
  });

  /// Whether the container is doing enough work to be worth colouring.
  bool get isBusy => cpuPercent >= 50;
}

/// Reads a `docker stats --no-stream` snapshot into a lookup by name.
///
/// Keyed by name because that is what joins it to the container list: the
/// listing is already showing names, and the two commands are separate calls a
/// moment apart. A row whose name is unreadable is dropped — it could not be
/// joined to anything, and a container card showing another container's CPU
/// would be worse than one showing none.
Map<String, ContainerStats> parseDockerStats(String output) {
  final stats = <String, ContainerStats>{};

  for (final line in output.split('\n')) {
    if (line.trim().isEmpty) continue;
    final parts = line.split('|');
    if (parts.length < 5) continue;

    final name = parts[0].trim();
    if (name.isEmpty) continue;

    stats[name] = ContainerStats(
      name: name,
      cpuPercent: _percent(parts[1]),
      memoryUsed: _usedMemory(parts[2]),
      memoryPercent: _percent(parts[3]),
      pids: int.tryParse(parts[4].trim()) ?? 0,
    );
  }

  return stats;
}

/// The container's own memory figure, out of `49.06MiB / 2GiB`.
///
/// The separator is ` / ` with spaces on both sides, which is how the daemon
/// writes it. Everything from there on is discarded on purpose — see
/// [ContainerStats.memoryUsed] for why the second half cannot be called a
/// limit. A value with no separator is returned whole rather than guessed at,
/// because splitting on a separator that was not there would invent a figure.
String _usedMemory(String raw) {
  final text = raw.trim();
  final at = text.indexOf(' / ');
  return at < 0 ? text : text.substring(0, at).trim();
}

/// Reads `12.34%` as a number.
///
/// The daemon writes the percent sign itself and always writes a number, so a
/// missing one means the row is not what it claims to be. Zero is returned
/// because the alternative — dropping the container from the map — would make
/// it vanish from a list that is showing it, and a resource figure of zero is
/// what "no activity" looks like anyway.
double _percent(String raw) =>
    double.tryParse(raw.trim().replaceAll('%', '')) ?? 0;
